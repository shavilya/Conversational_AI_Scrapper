"""
scraper_engine.py
Modular Scraping & Structured Extraction Engine for Conversational AI Scraper.
Powered by Crawl4AI and local Ollama (OpenAI-compatible API).
"""

import os
import json
import re
import asyncio
import concurrent.futures
from typing import Literal, Optional, List, Dict, Any

import httpx
from pydantic import BaseModel, Field, field_validator
from openai import OpenAI
from crawl4ai import AsyncWebCrawler, BrowserConfig, CrawlerRunConfig, CacheMode

# Disable Crawl4AI cloud notices
os.environ["CRAWL4AI_NO_CLOUD_NOTICE"] = "1"

# Default local LLM configuration
DEFAULT_OLLAMA_BASE_URL = "http://localhost:11434/v1"
DEFAULT_OLLAMA_SERVER = "http://localhost:11434"
DEFAULT_MODEL = "qwen2.5:7b"


class ScrapePlan(BaseModel):
    """Validated plan generated by the LLM from user prompt."""
    url: str = Field(description="Target URL to crawl")
    fields: List[str] = Field(default_factory=list, description="Target field names")
    output_format: Literal["table", "json", "csv"] = Field(default="table", description="Preferred output format")
    extraction_goal: str = Field(default="Extract entities", description="What entity or data to extract")
    max_items: Optional[int] = Field(default=None, description="Maximum number of items to extract")

    @field_validator("url")
    @classmethod
    def clean_url(cls, v: str) -> str:
        v = v.strip()
        if not v:
            return ""
        # Auto-prepend https:// if scheme is missing
        if not (v.startswith("http://") or v.startswith("https://")):
            v = "https://" + v
        return v

    @field_validator("fields")
    @classmethod
    def clean_fields(cls, v: List[str]) -> List[str]:
        cleaned = []
        for f in v:
            name = str(f).strip().replace(" ", "_").lower()
            name = re.sub(r"[^\w]", "", name)
            if name and name not in cleaned:
                cleaned.append(name)
        return cleaned or ["title", "details"]


def check_ollama_connection(server_url: str = DEFAULT_OLLAMA_SERVER) -> Dict[str, Any]:
    """Check if the local Ollama server is running and list available models."""
    try:
        clean_url = server_url.rstrip("/")
        resp = httpx.get(f"{clean_url}/api/tags", timeout=3.0)
        if resp.status_code == 200:
            data = resp.json()
            models = [m.get("name") for m in data.get("models", []) if m.get("name")]
            return {
                "connected": True,
                "models": models,
                "error": None
            }
        return {
            "connected": False,
            "models": [],
            "error": f"HTTP status {resp.status_code}"
        }
    except Exception as e:
        return {
            "connected": False,
            "models": [],
            "error": str(e)
        }


def _clean_json_text(text: str) -> str:
    """Strip markdown code blocks and trailing noise from LLM JSON responses."""
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.MULTILINE)
        text = re.sub(r"\s*```$", "", text, flags=re.MULTILINE)
    return text.strip()


def plan_scrape_task(
    user_prompt: str,
    model: str = DEFAULT_MODEL,
    base_url: str = DEFAULT_OLLAMA_BASE_URL
) -> ScrapePlan:
    """
    Step A: Analyze user natural-language prompt and generate a validated ScrapePlan.
    """
    client = OpenAI(base_url=base_url, api_key="ollama")

    system_prompt = (
        "You are an expert web scraping planner. Analyze the user's natural language request and extract "
        "the scraping specifications. Return ONLY a valid JSON object matching this schema:\n"
        "{\n"
        '  "url": "full URL or domain (e.g. https://books.toscrape.com). If no URL or domain was provided, return empty string \"\"",\n'
        '  "fields": ["list", "of", "field", "names", "in", "snake_case"],\n'
        '  "output_format": "table" | "json" | "csv" (default to "table" if not explicitly specified),\n'
        '  "extraction_goal": "brief description of items being extracted",\n'
        '  "max_items": integer or null (e.g. 10 if user said "top 10", else null)\n'
        "}"
    )

    response = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        response_format={"type": "json_object"},
        temperature=0.0
    )

    raw_content = response.choices[0].message.content or "{}"
    cleaned = _clean_json_text(raw_content)

    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", cleaned, re.DOTALL)
        if match:
            data = json.loads(match.group(0))
        else:
            raise ValueError(f"Failed to parse LLM planning response into JSON: {raw_content}")

    # Validate with Pydantic
    plan = ScrapePlan(**data)

    # Double-check fallback URL if missing in LLM output but present in raw prompt
    if not plan.url:
        url_match = re.search(r"(?:https?://[^\s]+|[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}(?:/[^\s]*)?)", user_prompt)
        if url_match:
            candidate = url_match.group(0).rstrip(".,;!?:)'\"")
            plan.url = ScrapePlan.clean_url(candidate)

    return plan


async def _async_crawl_page(url: str, cache_mode: CacheMode = CacheMode.BYPASS) -> Dict[str, Any]:
    """Internal async crawler utilizing Crawl4AI."""
    browser_cfg = BrowserConfig(
        browser_type="chromium",
        headless=True,
        verbose=False
    )

    run_cfg = CrawlerRunConfig(
        cache_mode=cache_mode,
        word_count_threshold=1,
        remove_overlay_elements=False,
    )

    async with AsyncWebCrawler(config=browser_cfg) as crawler:
        result = await crawler.arun(url=url, config=run_cfg)
        if not result.success:
            err = getattr(result, "error_message", "Unknown crawl error")
            raise RuntimeError(f"Crawl failed for {url}: {err}")

        raw_md = getattr(result.markdown, "raw_markdown", None) or str(result.markdown or "")

        return {
            "success": True,
            "url": url,
            "markdown": raw_md,
            "title": getattr(result, "title", "") or "",
            "length": len(raw_md),
        }


def crawl_page(url: str, cache_mode: CacheMode = CacheMode.BYPASS) -> Dict[str, Any]:
    """
    Step B: Synchronous wrapper for Crawl4AI web crawler.
    Executes in a clean ThreadPoolExecutor to prevent asyncio loop conflicts in Streamlit.
    """
    if not url:
        raise ValueError("Cannot crawl an empty URL. Please specify a target webpage.")

    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as pool:
        future = pool.submit(asyncio.run, _async_crawl_page(url, cache_mode))
        return future.result()


def _chunk_markdown(text: str, chunk_size: int = 12000, overlap: int = 1000) -> List[str]:
    """Split markdown into overlapping chunks if it exceeds context budget."""
    if len(text) <= chunk_size:
        return [text]

    chunks = []
    start = 0
    while start < len(text):
        end = start + chunk_size
        chunk = text[start:end]
        chunks.append(chunk)
        if end >= len(text):
            break
        start += (chunk_size - overlap)
    return chunks


def extract_records(
    markdown: str,
    plan: ScrapePlan,
    model: str = DEFAULT_MODEL,
    base_url: str = DEFAULT_OLLAMA_BASE_URL
) -> List[Dict[str, Any]]:
    """
    Step C: Extract and validate requested fields from crawled Markdown into structured records.
    Uses local Ollama in JSON mode.
    """
    if not markdown.strip():
        return []

    client = OpenAI(base_url=base_url, api_key="ollama")
    chunks = _chunk_markdown(markdown)
    all_records: List[Dict[str, Any]] = []
    seen_identifiers = set()

    max_items = plan.max_items or 100
    fields_str = ", ".join(plan.fields)
    schema_fields = ", ".join(f'"{f}": "..."' for f in plan.fields)

    system_prompt = (
        "You are a precise data extractor. Extract the requested items from the webpage Markdown.\n"
        f"Return ONLY a valid JSON object matching this structure: {{\"data\": [{{{schema_fields}}}]}}.\n"
        f"Each item in 'data' must contain these exact fields: {fields_str}.\n"
        "Extract real values directly from the text. If a field value is not found, use null.\n"
        f"Extraction Goal: {plan.extraction_goal}."
    )

    for idx, chunk in enumerate(chunks):
        if len(all_records) >= max_items:
            break

        remaining = max_items - len(all_records)
        user_content = (
            f"Extraction Goal: {plan.extraction_goal}\n"
            f"Fields to extract: {fields_str}\n"
            f"Extract up to {remaining} item(s) from this webpage content:\n\n"
            f"{chunk}"
        )

        try:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_content}
                ],
                response_format={"type": "json_object"},
                temperature=0.0
            )

            raw_resp = response.choices[0].message.content or "{}"
            cleaned = _clean_json_text(raw_resp)
            data = json.loads(cleaned)

            # Robust extraction of list items
            items: List[Any] = []
            if isinstance(data, dict):
                if "data" in data and isinstance(data["data"], list) and len(data["data"]) > 0:
                    items = data["data"]
                else:
                    for k, v in data.items():
                        if isinstance(v, list) and len(v) > 0 and isinstance(v[0], dict):
                            items = v
                            break
                    if not items and any(f in data for f in plan.fields):
                        items = [data]
            elif isinstance(data, list):
                items = data

            for item in items:
                if not isinstance(item, dict):
                    continue

                # Standardize item keys to match plan.fields
                standardized = {}
                for field in plan.fields:
                    val = item.get(field)
                    if val is None:
                        for k, v in item.items():
                            if k.lower().replace(" ", "_") == field:
                                val = v
                                break
                    standardized[field] = val

                # Deduplication key based on first 2 non-empty values
                key_tuple = tuple(str(standardized.get(f, "")) for f in plan.fields[:2])
                if key_tuple not in seen_identifiers:
                    seen_identifiers.add(key_tuple)
                    all_records.append(standardized)

                if len(all_records) >= max_items:
                    break

        except Exception as e:
            print(f"Warning: Extraction error on section {idx + 1}: {e}")
            continue

    return all_records
